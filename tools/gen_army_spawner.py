def sgui(name, effect=None, shown="", valid="always = yes", saved=False):
    lines = [f"{name} = {{", "  scope = character"]
    if saved:
        lines.append("  saved_scopes = { maa_flag }")
    lines += [f"  is_shown = {{ ucm_single_player_trigger = yes {shown}}}", f"  is_valid = {{ {valid} }}"]
    if effect:
        lines.append(f"  effect = {{ {effect} }}")
    return "\n".join(lines + ["}", ""])


def build_sguis():
    parts = [HEADER, "",
             sgui("ucm_army_spawner_visible", shown="has_character_flag = ucm_army_spawner_open "),
             sgui("ucm_army_spawner_close", "ucm_army_spawner_close_effect = yes"),
             sgui("ucm_army_spawner_is_picked", shown="has_variable = ucm_army_pick var:ucm_army_pick = scope:maa_flag ", saved=True),
             sgui("ucm_army_spawner_pick", "set_variable = { name = ucm_army_pick value = scope:maa_flag }", saved=True),
             sgui("ucm_army_spawner_spawn", "ucm_army_spawner_spawn_effect = yes", valid="has_variable = ucm_army_pick")]
    for step in SIZE_STEPS:
        parts.append(sgui(size_sgui(step), f"set_variable = {{ name = ucm_army_size value = {{ value = var:ucm_army_size add = {step} "
                                f"min = 1 max = {MAX_SIZE} }} }}"))
    return "\n".join(parts)


def build_effects(by):
    types = sorted(k for keys in by.values() for k in keys)
    branches = []
    for i, key in enumerate(types):
        branches.append(f"  {'else_if' if i else 'if'} = {{ limit = {{ var:ucm_army_pick = flag:{key} }} "
                        f"scope:ucm_cheat_menu_target = {{ ucm_army_spawner_add_effect = {{ TYPE = {key} }} }} }}")
    branches.append("  else = { send_interface_toast = { type = event_toast_effect_bad title = ucm_army_spawner_fail_title "
                    "desc = ucm_army_spawner_fail_maa } }")
    dispatch = "\n".join(branches)
    return f"""{HEADER}

ucm_army_spawner_open_effect = {{
  ucm_military_ensure_target_effect = yes
  add_character_flag = ucm_army_spawner_open
  if = {{
    limit = {{ NOT = {{ has_variable = ucm_army_size }} }}
    set_variable = {{ name = ucm_army_size value = 1 }}
  }}
}}

ucm_army_spawner_close_effect = {{
  remove_character_flag = ucm_army_spawner_open
  remove_variable = ucm_army_pick
  if = {{
    limit = {{ has_global_variable = ucm_cheat_menu_recipient }}
    ucm_military_reopen_3085_effect = yes
  }}
}}

# Scope = player, the pick and the size live on the player.
ucm_army_spawner_spawn_effect = {{
  ucm_military_ensure_target_effect = yes
  if = {{
    limit = {{ exists = scope:ucm_cheat_menu_target }}
    ucm_army_spawner_dispatch_effect = yes
  }}
  else = {{
    send_interface_toast = {{ type = event_toast_effect_bad title = ucm_army_spawner_fail_title desc = ucm_army_spawner_fail_target }}
  }}
}}

# Scope = target. Fills a regiment of $TYPE$ that has room, else raises a new one, once per requested regiment.
# Stops at the first regiment the game refuses; any regiment added counts as success.
ucm_army_spawner_add_effect = {{
  set_local_variable = {{ name = ucm_army_left value = root.var:ucm_army_size }}
  while = {{
    limit = {{ local_var:ucm_army_left > 0 }}
    change_local_variable = {{ name = ucm_army_left subtract = 1 }}
    if = {{
      limit = {{ any_maa_regiment = {{ is_maa_type = $TYPE$ can_upgrade_maa = yes }} }}
      random_maa_regiment = {{
        limit = {{ is_maa_type = $TYPE$ can_upgrade_maa = yes }}
        change_maa_regiment_size = {{ size = 1 reinforce = yes }}
      }}
      set_local_variable = {{ name = ucm_army_added value = 1 }}
    }}
    else = {{
      set_local_variable = {{ name = ucm_army_before value = maa_regiments_count }}
      create_maa_regiment = {{ type = $TYPE$ check_can_recruit = no size = 1 }}
      if = {{
        limit = {{ maa_regiments_count > local_var:ucm_army_before }}
        set_local_variable = {{ name = ucm_army_added value = 1 }}
      }}
      else = {{
        set_local_variable = {{ name = ucm_army_left value = 0 }}
      }}
    }}
  }}
  if = {{
    limit = {{ has_local_variable = ucm_army_added }}
    root = {{ send_interface_toast = {{ type = event_toast_effect_good title = ucm_army_spawner_ok_title desc = ucm_army_spawner_ok_desc left_icon = scope:ucm_cheat_menu_target }} }}
  }}
  else = {{
    root = {{ send_interface_toast = {{ type = event_toast_effect_bad title = ucm_army_spawner_fail_title desc = ucm_army_spawner_fail_maa }} }}
  }}
}}

# One branch per type: the pick is a flag at runtime and create_maa_regiment needs the type at parse time.
ucm_army_spawner_dispatch_effect = {{
{dispatch}
}}
"""


def build_loc(lang):
    lines = [f"l_{lang}:"]
    lines += [f' ucm_army_spawner_{k}: "{v}"' for k, v in LOC[lang].items()]
    return "\n".join(lines) + "\n"


def write(rel, text, bom=True):
    path = os.path.join(MOD_DIR, rel)
    with open(path, "wb") as fh:
        fh.write((b"\xef\xbb\xbf" if bom else b"") + text.replace("\n", "\r\n").encode("utf-8"))
    print("wrote", rel)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--game-dir", default=os.environ.get("CK3_GAME_DIR"), help="CK3 game/ directory (or CK3_GAME_DIR)")
    args = ap.parse_args()
    if not args.game_dir or not os.path.isdir(os.path.join(args.game_dir, MAA_DIR)):
        sys.exit(f"--game-dir: no {MAA_DIR} under {args.game_dir!r}")
    by = load([args.game_dir, MOD_DIR])
    names = load_loc("english", args.game_dir, MOD_DIR)
    missing = [b for b in by if b not in names]
    if missing or FIRST_TAB not in by:
        sys.exit(f"base types without a label: {missing}; first tab {FIRST_TAB} present: {FIRST_TAB in by}")
    write(os.path.join("gui", "ucm_army_spawner.gui"), build_gui(by))
    write(os.path.join("common", "scripted_guis", "ucm_army_spawner_sgui.txt"), build_sguis())
    write(os.path.join("common", "scripted_effects", "ucm_army_spawner_effects.txt"), build_effects(by))
    for lang in LOC:
        write(os.path.join("localization", lang, f"ucm_army_spawner_l_{lang}.yml"), build_loc(lang))


if __name__ == "__main__":
    main()
