def load(dirs):
    """{base type: [men-at-arms type, ...]}, both sorted by key."""
    by = defaultdict(list)
    for f in effective_files(MAA_DIR, *dirs):
        for key, body in top_level_objects(f):
            m = re.search(r"^\s*type\s*=\s*(\w+)", body, re.M)
            if not m:
                sys.exit(f"men-at-arms type {key}: no base type")
            by[m.group(1)].append(key)
    return {base: sorted(keys) for base, keys in sorted(by.items())}


def flag_call(sgui, method, key):
    return f"[GetScriptedGui('{sgui}').{method}({SCOPE}.AddScope('maa_flag', MakeScopeFlag('{key}')).End)]"


def call(sgui, method="Execute"):
    return f"[GetScriptedGui('{sgui}').{method}({SCOPE}.End)]"


