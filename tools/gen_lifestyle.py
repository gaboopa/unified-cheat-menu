"""Generate the lifestyle editor from the CK3 lifestyle and perk databases: one page per lifestyle with a button that
adds XP and a grant/remove toggle per perk. Perk, tree and lifestyle names are the game's own localization keys.

Writes gui/ucm_lifestyle.gui and common/scripted_guis/ucm_lifestyle_gui_sgui.txt. The toggles call the effects in
common/scripted_effects/ucm_lifestyle_gui_effects.txt.

Run after a CK3 update:
    python tools/gen_lifestyle.py --game-dir <CK3>/game
or set CK3_GAME_DIR instead of passing the flag.
"""
import argparse
import os
import re
import sys

from ck3parse import effective_files, load_loc, top_level_objects

MOD_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GUI_REL = os.path.join("gui", "ucm_lifestyle.gui")
SGUI_REL = os.path.join("common", "scripted_guis", "ucm_lifestyle_gui_sgui.txt")
PERKS = os.path.join("common", "lifestyle_perks")
LIFESTYLES = os.path.join("common", "lifestyles")
XP = 1000
HEADER = "# AUTO-GENERATED by tools/gen_lifestyle.py from the CK3 perk database. Do not edit; rerun the script."
ROOT = "GuiScope.SetRoot(GetPlayer.MakeScope).End"
TARGET = "GetPlayer.MakeScope.Var('ucm_lifestyle_target').Char"


def depth_zero(body):
    """A block's body with its nested blocks removed, so `trait = x` inside a modifier doesn't match."""
    while True:
        flat = re.sub(r"\{[^{}]*\}", "", body)
        if flat == body:
            return flat
        body = flat


def field(flat, name):
    m = re.search(rf"\b{name}\s*=\s*(\w+)", flat)
    return m.group(1) if m else None


def load(game):
    """{lifestyle: {tree: [(perk, trait or None), ...]}} in the game's order; lifestyles without perks are left out."""
    data = {k: {} for f in effective_files(LIFESTYLES, game) for k, _ in top_level_objects(f)}
    for f in effective_files(PERKS, game):
        for perk, body in top_level_objects(f):
            flat = depth_zero(body)
            ls, tree = field(flat, "lifestyle"), field(flat, "tree")
            if ls not in data or not tree:
                sys.exit(f"{perk}: bad lifestyle/tree ({ls}, {tree})")
            data[ls].setdefault(tree, []).append((perk, field(flat, "trait")))
    return {ls: trees for ls, trees in data.items() if trees}


def perk_labels(perk, loc):
    """[(gender condition or "", loc key), ...]: one label, or a male and a female one for a gendered perk."""
    if f"{perk}_name" in loc:
        return [("", f"{perk}_name")]
    male, female = f"{perk}_male_name", f"{perk}_female_name"
    if male not in loc or female not in loc:
        sys.exit(f"no name localization for perk {perk}")
    return [(f"Not({TARGET}.IsFemale)", male), (f"{TARGET}.IsFemale", female)]


def sguis(data):
    gate = "is_shown = { ucm_single_player_trigger = yes }"
    L = [HEADER, "", "ucm_lifestyle_visible = {", "\tscope = character",
         "\tis_shown = { ucm_single_player_trigger = yes has_character_flag = ucm_lifestyle_open }", "}"]

    def sgui(name, *lines):
        L.extend(["", f"{name} = {{", "\tscope = character", f"\t{gate}", *[f"\t{x}" for x in lines], "}"])

    sgui("ucm_lifestyle_close", "effect = { ucm_close_lifestyle_gui_effect = yes }")
    for ls, trees in data.items():
        sgui(f"ucm_lifestyle_xp_{ls}", "is_valid = { exists = var:ucm_lifestyle_target }",
             f"effect = {{ var:ucm_lifestyle_target = {{ add_{ls}_xp = {XP} }} }}")
        for perk, trait in (p for ps in trees.values() for p in ps):
            sgui(f"ucm_lifestyle_has_{perk}",
                 f"is_valid = {{ exists = var:ucm_lifestyle_target var:ucm_lifestyle_target = {{ has_perk = {perk} }} }}")
            call = (f"ucm_lifestyle_toggle_trait_perk_effect = {{ PERK = {perk} TRAIT = {trait} }}" if trait
                    else f"ucm_lifestyle_toggle_perk_effect = {{ PERK = {perk} }}")
            sgui(f"ucm_lifestyle_toggle_{perk}", "is_valid = { exists = var:ucm_lifestyle_target }",
                 f"effect = {{ var:ucm_lifestyle_target = {{ {call} }} }}")
    return "\n".join(L) + "\n"


def text(key, visible="", *extra):
    return ["text_single = {", *([f'\tvisible = "[{visible}]"'] if visible else []), f'\ttext = "{key}"',
            *[f"\t{x}" for x in extra], "}"]


def perk_button(perk, loc):
    has = f"GetScriptedGui('ucm_lifestyle_has_{perk}').IsValid({ROOT})"
    row = ["margin = { 8 0 }", "spacing = 8"]
    for visible, key in perk_labels(perk, loc):
        row += text(key, visible, "layoutpolicy_horizontal = expanding", 'default_format = "#clickable"', "autoresize = no")
    row += text("ucm_lifestyle_remove", has) + text("ucm_lifestyle_grant", f"Not({has})")
    return ["button_standard_hover = {", "\tlayoutpolicy_horizontal = expanding", "\tsize = { 0 38 }", f'\tdown = "[{has}]"',
            f'''\tonclick = "[GetScriptedGui('ucm_lifestyle_toggle_{perk}').Execute({ROOT})]"''',
            "\thbox = {", *[f"\t\t{x}" for x in row], "\t}", "}"]


def page(ls, trees, loc):
    L = [f'''visible = "[GetVariableSystem.HasValue('ucm_lifestyle_page', '{ls}')]"''',
         "layoutpolicy_horizontal = expanding", "spacing = 3",
         "button_standard = {", "\tlayoutpolicy_horizontal = expanding", "\tsize = { 0 32 }", '\ttext = "ucm_lifestyle_add_xp"',
         f'''\tonclick = "[GetScriptedGui('ucm_lifestyle_xp_{ls}').Execute({ROOT})]"''', "}"]
    for tree, perks in trees.items():
        if f"{tree}_name" not in loc:
            sys.exit(f"no name localization for perk tree {tree}")
        L += text(f"{tree}_name", "", 'default_format = "#high"')
        for perk, _ in perks:
            L += perk_button(perk, loc)
    return ["vbox = {", *[f"\t{x}" for x in L], "}"]


def gui(data, loc):
    tabs = []
    for ls in data:
        if f"{ls}_name" not in loc:
            sys.exit(f"no name localization for lifestyle {ls}")
        tabs += ["button_tab = {", "\tlayoutpolicy_horizontal = expanding", "\tsize = { 0 36 }", f'\ttext = "{ls}_name"',
                 f'''\tonclick = "[GetVariableSystem.Set('ucm_lifestyle_page', '{ls}')]"''',
                 f'''\tdown = "[GetVariableSystem.HasValue('ucm_lifestyle_page', '{ls}')]"''', "}"]
    pages = [x for ls, trees in data.items() for x in page(ls, trees, loc)]

    def nest(lines, n):
        return ["\t" * n + x for x in lines]

    return "\n".join([
        HEADER, "", "window = {", '\tname = "ucm_lifestyle_gui_window"', "\tparentanchor = center", "\tsize = { 760 720 }",
        "\tlayer = top", "\tfilter_mouse = all", "\tmovable = yes", "\twidget = {", "\t\tsize = { 100% 100% }",
        "\t\tbackground = {", "\t\t\tusing = Background_Area_Dark", "\t\t}", "\t}", '\tdatacontext = "[GetVariableSystem]"',
        '\tdatacontext = "[GetPlayer]"', f'''\tvisible = "[GetScriptedGui('ucm_lifestyle_visible').IsShown({ROOT})]"''',
        "\tstate = {", "\t\tname = ucm_lifestyle_init", "\t\ttrigger_on_create = yes",
        f'''\t\ton_start = "[GetVariableSystem.Set('ucm_lifestyle_page', '{next(iter(data))}')]"''', "\t}",
        "\tvbox = {", "\t\tusing = Window_Margins", "\t\tlayoutpolicy_horizontal = expanding", "\t\tlayoutpolicy_vertical = expanding",
        "\t\tspacing = 6", "\t\theader_pattern = {", "\t\t\tlayoutpolicy_horizontal = expanding",
        '\t\t\tblockoverride "header_text" {', '\t\t\t\ttext = "ucm_lifestyle_title"', "\t\t\t}",
        '\t\t\tblockoverride "button_close" {', f'''\t\t\t\tonclick = "[GetScriptedGui('ucm_lifestyle_close').Execute({ROOT})]"''', "\t\t\t}", "\t\t}",
        "\t\thbox = {", "\t\t\tlayoutpolicy_horizontal = expanding", "\t\t\tspacing = 10", "\t\t\tmargin = { 4 0 }",
        "\t\t\tportrait_head_small = {", f'\t\t\t\tdatacontext = "[{TARGET}]"', "\t\t\t}",
        "\t\t\ttext_single = {", "\t\t\t\tlayoutpolicy_horizontal = expanding", f'\t\t\t\ttext = "[{TARGET}.GetShortUINameNoTooltip]"',
        '\t\t\t\tdefault_format = "#high"', "\t\t\t\tautoresize = yes", "\t\t\t}", "\t\t}",
        "\t\thbox = {", "\t\t\tlayoutpolicy_horizontal = expanding", "\t\t\tlayoutpolicy_vertical = expanding", "\t\t\tspacing = 10",
        "\t\t\tvbox = {", "\t\t\t\tminimumsize = { 180 0 }", "\t\t\t\tlayoutpolicy_vertical = expanding", "\t\t\t\tspacing = 4",
        *nest(tabs, 4), "\t\t\t\texpand = {}", "\t\t\t}",
        "\t\t\tscrollbox = {", "\t\t\t\tlayoutpolicy_horizontal = expanding", "\t\t\t\tlayoutpolicy_vertical = expanding",
        '\t\t\t\tblockoverride "scrollbox_content" {', *nest(pages, 5), "\t\t\t\t}", "\t\t\t}",
        "\t\t}", "\t}", "}"]) + "\n"


def write(path, content):
    with open(path, "wb") as fh:
        fh.write(b"\xef\xbb\xbf" + content.replace("\n", "\r\n").encode("utf-8"))
    print("wrote", os.path.relpath(path, MOD_DIR))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--game-dir", default=os.environ.get("CK3_GAME_DIR"), help="CK3 game/ directory (or CK3_GAME_DIR)")
    args = ap.parse_args()
    if not args.game_dir or not os.path.isdir(os.path.join(args.game_dir, PERKS)):
        sys.exit(f"--game-dir: no {PERKS} under {args.game_dir!r}")
    data = load(args.game_dir)
    # Names must exist in every language the game ships that the mod supports (the game has no Turkish).
    loc = set.intersection(*(set(load_loc(lang, args.game_dir)) for lang in ("english", "german", "russian", "simp_chinese")))
    write(os.path.join(MOD_DIR, GUI_REL), gui(data, loc))
    write(os.path.join(MOD_DIR, SGUI_REL), sguis(data))


if __name__ == "__main__":
    main()
