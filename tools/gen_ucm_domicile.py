"""Generate common/scripted_effects/ucm_domicile_effects.txt from the base game's domicile buildings:
the estate presets behind the menu's Economic, Military and Balanced buttons.

    python tools/gen_ucm_domicile.py [--game-dir <CK3>/game]      (or CK3_GAME_DIR)

Each preset maxes the main building, clears the external slots, builds its six chains, fills any spare
slots at random, then upgrades everything left: every track to its top tier (the first-declared branch
where a track splits) and new internal buildings while their parent has a free slot.
"""
import argparse
import glob
import os
import re

import ck3parse

MOD = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_GAME = r"C:\Program Files (x86)\Steam\steamapps\common\Crusader Kings III\game"
OUT = os.path.join(MOD, "common", "scripted_effects", "ucm_domicile_effects.txt")

# Top tier of the chains each preset builds, per domicile type. Spare slots are random.
EA = "east_asian_estate_"
JP = "japanese_"
PRESETS = {
    "estate": {
        "economy": ["grain_field_06", "workshop_carpenter_06", "storage_warehouse_04", "market_06", "tea_06", "vineyard_06"],
        "military": ["guardhouse_04", "stable_grand_06", "barracks_06", "grazing_land_06", "watchtower_06", "garden_leisure_06"],
        "balanced": ["grain_field_06", "workshop_carpenter_06", "storage_warehouse_04", "market_06", "stable_grand_06", "guardhouse_04"],
    },
    "east_asian_estate": {
        "economy": [EA + b for b in ("rice_field_06", "workshop_carpenter_06", "storage_warehouse_06", "market_06", "tea_06", "silk_06")],
        "military": [EA + b for b in ("gate_06", "stable_grand_06", "barracks_06", "grazing_land_06", "watchtower_06", "garden_leisure_06")],
        "balanced": [EA + b for b in ("rice_field_06", "workshop_carpenter_06", "storage_warehouse_06", "market_06", "stable_grand_06", "gate_06")],
    },
    "japanese_manor": {
        "economy": [JP + b for b in ("fields_06", "workshop_06", "tea_plantation_06", "stables_06", "tea_house_06", "garden_06")],
        "military": [JP + b for b in ("armory_06", "stables_06", "horse_pastures_06", "watch_house_06", "garden_06", "fields_06")],
        "balanced": [JP + b for b in ("fields_06", "workshop_06", "tea_plantation_06", "stables_06", "armory_06", "garden_06")],
    },
}
FILL = {"estate": "add_random_external_estate_building", "east_asian_estate": "add_random_external_east_asian_estate_building",
        "japanese_manor": "add_random_external_japanese_manor_building"}

# One step of a run of tiers on track $T$; {k} is the tier, {p} the one below it.
LADDER_STEP = {"add": "ucm_domicile_add_effect = { B = $T$_{k} }",
               "lower": "ucm_domicile_lower_effect = { B = $T$_{k} }",
               "upgrade": "ucm_domicile_upgrade_effect = { FROM = $T$_{p} TO = $T$_{k} }"}

HEADER = """# Generated by tools/gen_ucm_domicile.py from the base game's domicile buildings. Don't edit by hand.
# add_domicile_building ignores cost and construction time. Effects below take the domicile as scope,
# except ucm_domicile_holder_effect and ucm_domicile_preset_*_effect, which take a character.

ucm_domicile_add_effect = {
	if = {
		limit = { NOT = { has_domicile_building_or_higher = $B$ } }
		add_domicile_building = $B$
	}
}

ucm_domicile_upgrade_effect = {
	if = {
		limit = {
			has_domicile_building_or_higher = $FROM$
			NOT = { has_domicile_building_or_higher = $TO$ }
		}
		add_domicile_building = $TO$
	}
}

ucm_domicile_add_internal_effect = {
	if = {
		limit = {
			has_domicile_building_or_higher = $PARENT$
			NOT = { has_domicile_building_or_higher = $B$ }
			domicile_building_has_free_internal_slot = $PARENT$
		}
		add_domicile_building = $B$
	}
}

ucm_domicile_lower_effect = {
	if = {
		limit = { has_domicile_building = $B$ }
		lower_domicile_building_no_refund = $B$
	}
}

ucm_domicile_remove_effect = {
	if = {
		limit = { has_domicile_building = $B$ }
		remove_domicile_building_no_refund = $B$
	}
}

# Saves the character whose estate a preset changes: the target, else, if the target has no domicile at all,
# their house head or oldest house member with one (administrative estates often sit with the noble family).
ucm_domicile_holder_effect = {
	if = {
		limit = { %(holds)s }
		save_scope_as = ucm_domicile_holder
	}
	else_if = {
		limit = { has_domicile = no house.house_head ?= { %(holds)s } }
		house.house_head = { save_scope_as = ucm_domicile_holder }
	}
	else_if = {
		limit = { has_domicile = no house ?= { any_house_member = { %(holds)s } } }
		house = {
			ordered_house_member = {
				limit = { %(holds)s }
				order_by = age
				save_scope_as = ucm_domicile_holder
			}
		}
	}
}
"""


def load_buildings(game):
    """{domicile type: {building: (slot type, previous building)}}, in declaration order."""
    out = {t: {} for t in PRESETS}
    for path in sorted(glob.glob(os.path.join(game, "common", "domiciles", "buildings", "*.txt"))):
        with open(path, encoding="utf-8-sig") as fh:
            text = fh.read()
        for key, body in ck3parse.top_level_objects_text(text):
            allowed = re.search(r"allowed_domicile_types\s*=\s*\{([^}]*)\}", body)
            slot = re.search(r"slot_type\s*=\s*(\w+)", body)
            prev = re.search(r"previous_building\s*=\s*(\w+)", body)
            for t in allowed.group(1).split() if allowed else []:
                if t in out:
                    out[t][key] = (slot.group(1) if slot else "external", prev.group(1) if prev else None)
    return out


def walk(buildings, slot):
    """Buildings of a slot type, each after its previous tier."""
    done = []

    def visit(b):
        if b not in done and buildings[b][0] == slot:
            done.append(b)
            for k, (_, prev) in buildings.items():
                if prev == b:
                    visit(k)

    for b, (s, prev) in buildings.items():
        if s == slot and (prev is None or buildings[prev][0] != slot):
            visit(b)
    return done


def chain(buildings, tip):
    """The tiers leading to tip, lowest first."""
    out = [tip]
    while buildings[out[0]][1]:
        out.insert(0, buildings[out[0]][1])
    return out


def upgrades(buildings, slot):
    """Steps upgrading each track of a slot type; a split takes its first branch, unless already on another."""
    steps = []
    for b in walk(buildings, slot):
        prev = buildings[b][1]
        if prev is None:
            continue
        if buildings[prev][0] != slot:
            if slot == "internal":
                steps.append(f"ucm_domicile_add_internal_effect = {{ PARENT = {prev} B = {b} }}")
            continue
        siblings = [k for k, (s, p) in buildings.items() if p == prev and s == slot]
        if b != siblings[0]:
            continue
        if len(siblings) > 1:
            others = " ".join(f"has_domicile_building_or_higher = {k}" for k in siblings[1:])
            steps.append(f"if = {{ limit = {{ NOR = {{ {others} }} }} ucm_domicile_upgrade_effect = {{ FROM = {prev} TO = {b} }} }}")
        elif tier(prev) == (tier(b)[0], tier(b)[1] - 1):
            steps.append(("upgrade", b))
        else:  # The track continues under another name.
            steps.append(f"ucm_domicile_upgrade_effect = {{ FROM = {prev} TO = {b} }}")
    return steps


def clear_steps(buildings):
    """Steps emptying the external slots, starting with the internal buildings inside them."""
    def external_root(b):
        while buildings[b][0] == "internal":
            b = buildings[b][1]
        return buildings[b][0] == "external"

    inner = [b for b in reversed(walk(buildings, "internal")) if external_root(b)]
    return [f"ucm_domicile_remove_effect = {{ B = {b} }}" if buildings[b][1] is None or buildings[buildings[b][1]][0] != buildings[b][0]
            else ("lower", b) for b in inner + list(reversed(walk(buildings, "external")))]


def tier(b):
    """(stem, tier number) of a building key like workshop_mason_03."""
    stem, _, n = b.rpartition("_")
    return stem, int(n)


def compress(steps, ladders):
    """Script lines for steps, one call per run of tiers on a track. ladders collects the run effects used:
    (kind, first tier, last tier), lowering runs going downwards."""
    lines, i = [], 0
    while i < len(steps):
        step = steps[i]
        if isinstance(step, str):
            lines.append(step)
            i += 1
            continue
        kind, b = step
        stem, first = tier(b)
        last, j, direction = first, i + 1, -1 if kind == "lower" else 1
        while j < len(steps) and steps[j] == (kind, f"{stem}_{last + direction:02d}"):
            last += direction
            j += 1
        if j - i == 1:
            lines.append(LADDER_STEP[kind].replace("$T$", stem).replace("{k}", f"{first:02d}").replace("{p}", f"{first - 1:02d}"))
        else:
            ladders.add((kind, first, last))
            lines.append(f"ucm_domicile_{kind}_{first}_{last}_effect = {{ T = {stem} }}")
        i = j
    return lines


def ladder(kind, first, last):
    direction = -1 if last < first else 1
    return effect(f"ucm_domicile_{kind}_{first}_{last}_effect",
                  [LADDER_STEP[kind].replace("{k}", f"{k:02d}").replace("{p}", f"{k - 1:02d}") for k in range(first, last + direction, direction)])


def effect(name, lines):
    return f"{name} = {{\n" + "".join(f"\t{l}\n" for l in lines) + "}\n"


def generate(buildings):
    types = " ".join(f"is_domicile_type = {t}" for t in PRESETS)
    holds = f"is_alive = yes domicile ?= {{ OR = {{ {types} }} }}"
    out, ladders = [], set()
    for t, own in buildings.items():
        missing = [b for p in PRESETS[t].values() for b in p if b not in own]
        if missing:
            raise SystemExit(f"{t}: not in the game's domicile buildings: {missing}")
        out.append(effect(f"ucm_domicile_{t}_main_effect", compress([("add", b) for b in walk(own, "main")], ladders)))
        out.append(effect(f"ucm_domicile_{t}_clear_external_effect", compress(clear_steps(own), ladders)))
        out.append(effect(f"ucm_domicile_{t}_upgrade_all_effect", compress(upgrades(own, "external") + upgrades(own, "internal"), ladders)))
        for preset, tips in PRESETS[t].items():
            lines = [f"ucm_domicile_{t}_main_effect = yes", f"ucm_domicile_{t}_clear_external_effect = yes"]
            lines += compress([("add", b) for tip in tips for b in chain(own, tip)], ladders)
            lines += [f"while = {{ count = 40 limit = {{ free_external_domicile_building_slots >= 1 }} {FILL[t]} = yes }}",
                      f"ucm_domicile_{t}_upgrade_all_effect = yes"]
            out.append(effect(f"ucm_domicile_{t}_{preset}_effect", lines))
    for preset in ("economy", "military", "balanced"):
        lines = ["ucm_domicile_holder_effect = yes", "if = {", "\tlimit = { exists = scope:ucm_domicile_holder }", "\tscope:ucm_domicile_holder = {",
                 "\t\thidden_effect = {", "\t\t\tdomicile = {", "\t\t\t\tswitch = {", "\t\t\t\t\ttrigger = is_domicile_type"]
        lines += [f"\t\t\t\t\t{t} = {{ ucm_domicile_{t}_{preset}_effect = yes }}" for t in PRESETS]
        lines += ["\t\t\t\t}", "\t\t\t}", "\t\t}"]
        lines += [f"\t\tremove_character_modifier = ucm_domicile_preset_{p}_bonus_modifier" for p in ("economy", "military", "balanced")]
        lines += [f"\t\tadd_character_modifier = ucm_domicile_preset_{preset}_bonus_modifier", "\t}", "}"]
        out.append(effect(f"ucm_domicile_preset_{preset}_effect", lines))
    return "\n".join([HEADER % {"holds": holds}, *[ladder(*l) for l in sorted(ladders)], *out])


def self_check():
    own = {"m_01": ("main", None), "a_01": ("external", None), "a_02": ("external", "a_01"), "a_03": ("external", "a_02"), "x_04": ("external", "a_03"),
           "y_04": ("external", "a_03"), "y_05": ("external", "y_04"), "y_06": ("external", "y_05"), "i_01": ("internal", "m_01"), "i_02": ("internal", "i_01")}
    assert chain(own, "y_05") == ["a_01", "a_02", "a_03", "y_04", "y_05"]
    ladders = set()
    ext = compress(upgrades(own, "external"), ladders)
    assert ext[0] == "ucm_domicile_upgrade_2_3_effect = { T = a }"
    renamed = {"a_01": ("internal", None), "a_02": ("internal", "a_01"), "b_03": ("internal", "a_02"), "b_04": ("internal", "b_03")}
    assert "FROM = a_02 TO = b_03" in " ".join(compress(upgrades(renamed, "internal"), set()))
    assert "NOR = { has_domicile_building_or_higher = y_04 }" in ext[1] and "TO = x_04" in ext[1]
    assert ext[2] == "ucm_domicile_upgrade_5_6_effect = { T = y }" and len(ext) == 3
    assert compress(upgrades(own, "internal"), ladders) == ["ucm_domicile_add_internal_effect = { PARENT = m_01 B = i_01 }",
                                                            "ucm_domicile_upgrade_effect = { FROM = i_01 TO = i_02 }"]
    assert compress([("lower", "y_06"), ("lower", "y_05"), ("lower", "x_04")], ladders)[0] == "ucm_domicile_lower_6_5_effect = { T = y }"
    assert "FROM = $T$_04 TO = $T$_05" in ladder("upgrade", 5, 6) and "$T$_05" in ladder("lower", 6, 5)
    assert clear_steps({"m_01": ("main", None), "e_01": ("external", None), "e_02": ("external", "e_01"), "i_01": ("internal", "e_01"), "j_01": ("internal", "m_01")}) == [
        "ucm_domicile_remove_effect = { B = i_01 }", ("lower", "e_02"), "ucm_domicile_remove_effect = { B = e_01 }"]
    print("gen_ucm_domicile self-check OK")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--game-dir", default=os.environ.get("CK3_GAME_DIR", DEFAULT_GAME))
    ap.add_argument("--self-check", action="store_true")
    args = ap.parse_args()
    if args.self_check:
        return self_check()
    text = generate(load_buildings(args.game_dir))
    with open(OUT, "w", encoding="utf-8-sig", newline="\n") as fh:
        fh.write(text)
    print(f"wrote {OUT} ({len(text)} chars)")


if __name__ == "__main__":
    main()
