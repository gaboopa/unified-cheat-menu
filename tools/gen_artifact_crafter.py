def write(rel, text):
    with open(os.path.join(MOD_DIR, rel), "wb") as fh:
        fh.write(b"\xef\xbb\xbf" + text.replace("\n", "\r\n").encode("utf-8"))
    print("wrote", rel)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--game-dir", default=os.environ.get("CK3_GAME_DIR"), help="CK3 game/ directory (or CK3_GAME_DIR)")
    args = ap.parse_args()
    if not args.game_dir or not os.path.isdir(os.path.join(args.game_dir, FORMATS)):
        sys.exit(f"--game-dir: no {FORMATS} under {args.game_dir!r}")
    layer = layers(args.game_dir)
    write("common/modifiers/ucm_craft_stack_modifiers.txt", modifiers(layer))
    write("common/scripted_effects/ucm_craft_generated_effects.txt", effects(tiers(args.game_dir, layer)))
    write("common/scripted_guis/ucm_craft_generated_guis.txt", guis())
    write("common/customizable_localization/ucm_craft_labels.txt", labels())
    write("gui/ucm_artifact_craft.gui", craft_gui())
    write("gui/ucm_artifact_repair.gui", repair_gui())
    write("gui/ucm_artifact_shared.gui", shared_gui())


if __name__ == "__main__":
    main()
