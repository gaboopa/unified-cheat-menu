def row(onclick, label, icons, tooltip, down="", contexts=(), height=52):
    """One list row: a button with icons and a name."""
    ctx = "".join(f'\n                datacontext = "[{c}]"' for c in contexts)
    dn = f'\n                down = "[{down}]"' if down else ""
    return f"""              button_standard_hover = {{{ctx}
                layoutpolicy_horizontal = expanding
                size = {{ 0 {height} }}{dn}
                onclick = "[{onclick}]"
                {tooltip}
                hbox = {{
                  layoutpolicy_horizontal = expanding
                  margin = {{ 8 0 }}
                  spacing = 8
                  {icons}
                  text_single = {{ layoutpolicy_horizontal = expanding raw_text = "{label}" default_format = "#clickable" autoresize = no }}
                }}
              }}"""


def rows(datamodel, body, visible=""):
    """A vbox of rows from a global list."""
    vis = f'\n          visible = "[{visible}]"' if visible else ""
    return f"""        vbox = {{
          layoutpolicy_horizontal = expanding{vis}
          datamodel = "[GetGlobalList('{datamodel}')]"
          item = {{
{body}
          }}
        }}"""


def scrollbox(content, extra=""):
    return f"""    scrollbox = {{{extra}
      layoutpolicy_horizontal = expanding
      layoutpolicy_vertical = expanding
      blockoverride "scrollbox_content" {{
{content}
      }}
    }}"""


