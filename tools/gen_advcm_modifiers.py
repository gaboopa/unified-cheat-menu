"""Generate the artifact crafting slot modifiers from the slot list and the CK3 modifier formats.

Writes common/modifiers/ucm_acm_advcm_generated_modifiers.txt: an advcm_<slot>_1 / advcm_<slot>_neg_1 stacking
pair for every slot in ucm_acm_artifact_slot_sync_effects.txt (POS = advcm_<slot>_1, in VAL order).

From each modifier's common/modifier_definition_formats entry:
- step: 0.01 when it is shown as a percent or with 2+ decimals (the default when it has no entry), else 1;
- sign: for `color = bad` modifiers (upkeep, costs, stress, ...) *_1 lowers the value, so + is always the good way.

Run after a CK3 update, or after adding a slot:
    python tools/gen_advcm_modifiers.py --game-dir <CK3>/game
or set CK3_GAME_DIR instead of passing the flag.
"""
import argparse
import os
import re
import sys

from ck3parse import effective_files, top_level_objects

MOD_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_REL = os.path.join("common", "modifiers", "ucm_acm_advcm_generated_modifiers.txt")
SLOTS_REL = os.path.join("common", "scripted_effects", "ucm_acm_artifact_slot_sync_effects.txt")
FORMATS = os.path.join("common", "modifier_definition_formats")
MODIFIER_OF = {"prowess": "prowess_no_portrait"}  # slot name -> modifier key, where they differ


def slots():
    with open(os.path.join(MOD_DIR, SLOTS_REL), encoding="utf-8-sig") as fh:
        found = re.findall(r"POS = advcm_(\w+)_1 NEG = advcm_\1_neg_1 VAL = (\d+)", fh.read())
    if not found:
        sys.exit(f"{SLOTS_REL}: no POS/NEG/VAL slot lines found")
    return [s for s, _ in sorted(found, key=lambda sv: int(sv[1]))]


def build(game):
    formats = {k: b for f in effective_files(FORMATS, game) for k, b in top_level_objects(f)}
    L = ["# AUTO-GENERATED by tools/gen_advcm_modifiers.py (slots: ucm_acm_artifact_slot_sync_effects.txt, step and",
         "# sign: CK3 modifier formats). Do not edit; rerun the script. Modifier set from workshop #2752613114 (advcm).",
         "# Each +1 stack uses *_1; negative stacks use *_neg_1 (see ucm_acm_modifier_inject_*). For color = bad",
         "# modifiers (upkeep, costs, stress, ...) *_1 lowers the value, so + is always the good way.", ""]
    for s in slots():
        mod = MODIFIER_OF.get(s, s)
        fmt = formats.get(mod)
        if fmt is None:
            print(f"  note: {mod} has no modifier format (code-defined?); using 2 decimals")
            fmt = ""
        m = re.search(r"\bdecimals\s*=\s*(\d+)", fmt)
        step = 0.01 if re.search(r"\bpercent\s*=\s*yes", fmt) or int(m.group(1) if m else 2) >= 2 else 1
        sign = -1 if re.search(r"\bcolor\s*=\s*bad", fmt) else 1
        for name, v in ((f"advcm_{s}_neg_1", -sign * step), (f"advcm_{s}_1", sign * step)):
            L += [f"{name} = {{{mod} = {v:g} stacking = yes}}", ""]
    return "\n".join(L)


def write(path, text):
    with open(path, "wb") as fh:
        fh.write(b"\xef\xbb\xbf" + text.replace("\n", "\r\n").encode("utf-8"))
    print("wrote", os.path.relpath(path, MOD_DIR))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--game-dir", default=os.environ.get("CK3_GAME_DIR"), help="CK3 game/ directory (or CK3_GAME_DIR)")
    args = ap.parse_args()
    if not args.game_dir or not os.path.isdir(os.path.join(args.game_dir, FORMATS)):
        sys.exit(f"--game-dir: no {FORMATS} under {args.game_dir!r}")
    write(os.path.join(MOD_DIR, OUT_REL), build(args.game_dir))


if __name__ == "__main__":
    main()
