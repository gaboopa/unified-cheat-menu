"""Generate the artifact crafter and editor: stack modifiers, effects, scripted GUIs, labels and windows.

The crafter has five modifier slots. A slot holds a SLOTS entry (1-based index, 0 = empty) and an amount: the number
of times its one-layer modifier is added. Step and sign of a layer come from common/modifier_definition_formats:
0.01 when shown as a percent or with 2+ decimals (the default when it has no entry), else 1; `color = bad` modifiers
are negated, so more layers is always better. Vanilla artifact_<x>_<n>_modifier tiers are mapped to layers from
common/modifiers, which is how an artifact the crafter didn't make fills its slots in the editor.

Run after a CK3 update, or after changing SLOTS or TYPES:
    python tools/gen_artifact_crafter.py --game-dir <CK3>/game
or set CK3_GAME_DIR instead of passing the flag.
"""
