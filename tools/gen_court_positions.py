"""Generate the one-click court reshuffle position lists from the CK3 court position types.

Writes common/scripted_effects/ucm_positions_court_slots_generated.txt: revoke and appoint lists over every
`*_court_position` type the game defines (camp officers are a separate system and left out). Positions are
appointed in list order, so PRIORITY comes first and any other type follows in game file order.
ucm_positions_try_appoint_court_slot_strict_loose_spawn_effect checks can_employ_court_position_type, so
DLC/government-only positions are safe to list.

Run after a CK3 update:
    python tools/gen_court_positions.py --game-dir <CK3>/game
or set CK3_GAME_DIR instead of passing the flag.
"""
import argparse
import os
import sys

from ck3parse import effective_files, top_level_objects

MOD_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_REL = os.path.join("common", "scripted_effects", "ucm_positions_court_slots_generated.txt")
TYPES = os.path.join("common", "court_positions", "types")
PRIORITY = """court_physician court_tutor wet_nurse bodyguard champion master_assassin chronicler yeke_jarquchi
foreign_emissary court_gardener court_scholar court_jester chief_eunuch royal_architect travel_leader antiquarian seneschal
master_of_horse master_of_hunt fire_dragon_engineer court_brewmaster lady_in_waiting court_artificer minister_bureaucrat
cupbearer food_taster garuda bookmaker akolouthos court_guru yurtchi keeper_of_the_horses court_brahmin grand_mentor
grand_preceptor keeper_of_the_harem court_poet grand_guardian executioner high_almoner siege_engineer cultural_emissary
favored_minister khlon_glan cherbi boyan court_astrologer court_musician""".split()


def positions(game):
    found = [k for f in effective_files(TYPES, game, MOD_DIR) for k, _ in top_level_objects(f) if k.endswith("_court_position")]
    first = [f"{p}_court_position" for p in PRIORITY]
    gone = [p for p in first if p not in found]
    if gone:
        print("  note: no longer in the game, dropped:", ", ".join(gone))
    return [p for p in first if p in found] + [p for p in found if p not in first]


def block(name, call, ps):
    return [f"{name} = {{", "  scope:ucm_pos_reshuffle_liege = {"] + [f"    {call} = {{ COURT_POS = {p} }}" for p in ps] + ["  }", "}", ""]


def build(ps):
    L = ["# AUTO-GENERATED by tools/gen_court_positions.py from the CK3 court position types. Do not edit; rerun the script.",
         "# 原版职位始终处理；变身大明 / 东方王朝职位仅在 ucm_compat_*_loaded 为真时调用（见 ucm_compat_triggers.txt）。", "",
         "ucm_positions_revoke_one_court_slot_fully_effect = {", "  scope:ucm_pos_reshuffle_liege = {", "    while = {",
         "      limit = { employs_court_position = $COURT_POS$ }", "      random_court_position_holder = {",
         "        type = $COURT_POS$", "        save_scope_as = ucm_pos_revoke_holder", "      }", "      if = {",
         "        limit = { exists = scope:ucm_pos_revoke_holder }", "        revoke_court_position = {",
         "          recipient = scope:ucm_pos_revoke_holder", "          court_position = $COURT_POS$", "        }",
         "        clear_saved_scope = ucm_pos_revoke_holder", "      }", "    }", "  }", "}", ""]
    L += block("ucm_positions_revoke_core_named_court_positions_effect", "ucm_positions_revoke_one_court_slot_fully_effect", ps)
    L += ["ucm_positions_revoke_all_named_court_positions_effect = {", "  scope:ucm_pos_reshuffle_liege = {",
          "    ucm_positions_revoke_core_named_court_positions_effect = yes", "  }", "}", ""]
    L += block("ucm_positions_appoint_core_named_court_positions_strict_loose_spawn_effect",
               "ucm_positions_try_appoint_court_slot_strict_loose_spawn_effect", ps)
    L += block("ucm_positions_appoint_orient_named_court_positions_strict_loose_spawn_effect", "", [])
    L += ["ucm_positions_appoint_all_named_court_positions_strict_loose_spawn_effect = {", "  scope:ucm_pos_reshuffle_liege = {",
          "    ucm_positions_appoint_core_named_court_positions_strict_loose_spawn_effect = yes", "    if = {",
          "      limit = { ucm_compat_orient_loaded_trigger = yes }",
          "      ucm_positions_appoint_orient_named_court_positions_strict_loose_spawn_effect = yes", "    }", "  }", "}"]
    return "\n".join(L) + "\n"


def write(path, text):
    with open(path, "wb") as fh:
        fh.write(b"\xef\xbb\xbf" + text.replace("\n", "\r\n").encode("utf-8"))
    print("wrote", os.path.relpath(path, MOD_DIR))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--game-dir", default=os.environ.get("CK3_GAME_DIR"), help="CK3 game/ directory (or CK3_GAME_DIR)")
    args = ap.parse_args()
    if not args.game_dir or not os.path.isdir(os.path.join(args.game_dir, TYPES)):
        sys.exit(f"--game-dir: no {TYPES} under {args.game_dir!r}")
    write(os.path.join(MOD_DIR, OUT_REL), build(positions(args.game_dir)))


if __name__ == "__main__":
    main()
