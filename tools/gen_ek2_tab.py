"""Regenerate the Elder Kings 2 tab's scripted GUIs, script values and English loc from gen_ucm_main_menu's EK2 lists.

The main mod gets is_shown = no stubs and the compatch gets the real effects at the same paths, so the tab
only appears with EK2. Run gen_ucm_main_menu.py too after changing the lists:
    python tools/gen_ek2_tab.py
"""
import os

from gen_ucm_main_menu import EK2_LIFESTYLES, EK2_PERK_RANKS, EK2_TREES, MOD_DIR

SHOWN = "is_shown = { ucm_single_player_trigger = yes }"
VALID = "is_valid = { ucm_menu_target_valid_trigger = yes }"


def perk(tree, rank):
    return f"{tree}_{rank}_perk"


def add_perk(p):
    return f"if = {{ limit = {{ NOT = {{ has_perk = {p} }} }} add_perk = {p} }}"


def gui(name, *body, valid=VALID):
    lines = "\n".join(f"\t\t\t{b}" for b in body)
    return f"{name} = {{\n\tscope = character\n\t{SHOWN}\n\t{valid}\n\teffect = {{\n\t\tvar:ucm_target = {{\n{lines}\n\t\t}}\n\t}}\n}}\n"


def effects():
    """(name, body) of every button except the single-perk ones, which also disable once owned."""
    out = [
        ("ucm_ek2_max_arcana", [
            "# EK2 reads base_arcana_* only once at game start; afterwards the base lives in this variable.",
            "if = {", "\tlimit = { arcana_base < 12 }", "\tset_variable = { name = arcana_base value = 12 }", "}",
            *[f"if = {{ limit = {{ has_trait = arcana_bad_{n} }} remove_trait = arcana_bad_{n} }}" for n in (1, 2, 3)],
            "add_trait = arcana_good_3",
            "if = { limit = { NOT = { has_trait = magickal_education } } add_trait = magickal_education }",
            "add_trait_xp = { trait = magickal_education value = 100 }",
        ]),
        ("ucm_ek2_refill_magicka", ["set_variable = { name = magicka value = magicka_max }"]),
        ("ucm_ek2_arcana_up", ["add_arcana_skill = { VALUE = ucm_step_value }"]),
        ("ucm_ek2_arcana_down", ["add_arcana_skill = { VALUE = ucm_step_negative_value }"]),
        ("ucm_ek2_magicka_up", ["add_magicka = { VALUE = ucm_step_value }"]),
        ("ucm_ek2_magicka_down", [
            "add_magicka = { VALUE = ucm_step_negative_value }",
            "if = { limit = { var:magicka < 0 } set_variable = { name = magicka value = 0 } }",
        ]),
    ]
    for ls in EK2_LIFESTYLES:
        out.append((f"ucm_ek2_{ls}_point", [f"add_{ls}_lifestyle_perk_points = 1"]))
        out.append((f"ucm_ek2_{ls}_xp", [f"add_{ls}_lifestyle_xp = 1000"]))
    for t in EK2_TREES:
        out.append((f"ucm_ek2_perks_{t}", [add_perk(perk(t, r)) for r in EK2_PERK_RANKS]))
    return out


def write(rel, text, bom=False):
    path = os.path.join(MOD_DIR, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as fh:
        fh.write((b"\xef\xbb\xbf" if bom else b"") + text.encode("utf-8"))


def main():
    perks = [perk(t, r) for t in EK2_TREES for r in EK2_PERK_RANKS]
    names = ["ucm_ek2_tab"] + [n for n, _ in effects()] + [f"ucm_ek2_perk_{p}" for p in perks]
    head = "# AUTO-GENERATED by tools/gen_ek2_tab.py.\n"
    write("common/scripted_guis/ucm_ek2_sguis.txt",
          head + "# Stubs: compat/ek2 ships the real effects at this path; without it the tab stays hidden.\n"
          + "".join(f"{n} = {{ scope = character is_shown = {{ always = no }} }}\n" for n in names))
    blocks = [f"ucm_ek2_tab = {{\n\tscope = character\n\t{SHOWN}\n}}\n"]
    blocks += [gui(n, *b) for n, b in effects()]
    blocks += [gui(f"ucm_ek2_perk_{p}", f"add_perk = {p}",
                   valid=f"is_valid = {{ ucm_menu_target_valid_trigger = yes var:ucm_target = {{ NOT = {{ has_perk = {p} }} }} }}")
               for p in perks]
    write("compat/ek2/common/scripted_guis/ucm_ek2_sguis.txt", head + "\n".join(blocks))

    write("common/script_values/ucm_ek2_values.txt",
          head + "# Stubs for the tab's readouts; compat/ek2 overrides this file.\nucm_ek2_arcana_value = 0\nucm_ek2_magicka_value = 0\n")
    write("compat/ek2/common/script_values/ucm_ek2_values.txt",
          head + "ucm_ek2_arcana_value = { value = arcana }\n"
          + "ucm_ek2_magicka_value = {\n\tvalue = 0\n\tif = {\n\t\tlimit = { exists = var:magicka }\n\t\tadd = var:magicka\n\t}\n}\n")

    loc = {
        "UCM_TAB_EK2": "Elder Kings 2", "UCM_SEC_EK2_ARCANA": "Arcana & Magicka", "UCM_SEC_EK2_LIFESTYLE": "Lifestyle Progress",
        "UCM_SEC_EK2_SCHOOLS": "Magic Schools", "UCM_SEC_EK2_DARK": "Dark Arts",
        "UCM_SKILL_ARCANA": "Arcana", "UCM_SKILL_MAGICKA": "Magicka",
        "ucm_ek2_max_arcana": "Max Arcana",
        "ucm_ek2_max_arcana_tt": "Raises base arcana to 12, gives the top gifted arcana trait and full magickal education, and removes bad arcana traits.",
        "ucm_ek2_refill_magicka": "Refill Magicka", "ucm_ek2_refill_magicka_tt": "Sets current magicka to the maximum.",
        "ucm_ek2_arcana_up": "+", "ucm_ek2_arcana_up_tt": "Raise arcana by the step size.",
        "ucm_ek2_arcana_down": "−", "ucm_ek2_arcana_down_tt": "Lower arcana by the step size.",
        "ucm_ek2_magicka_up": "+", "ucm_ek2_magicka_up_tt": "Raise magicka by the step size, up to the maximum.",
        "ucm_ek2_magicka_down": "−", "ucm_ek2_magicka_down_tt": "Lower magicka by the step size.",
    }
    for ls, label in EK2_LIFESTYLES.items():
        loc[f"ucm_ek2_{ls}_point"] = f"+1 {label} Perk Point"
        loc[f"ucm_ek2_{ls}_point_tt"] = "Gives one perk point to spend in the lifestyle screen."
        loc[f"ucm_ek2_{ls}_xp"] = f"+1000 {label} XP"
        loc[f"ucm_ek2_{ls}_xp_tt"] = f"Adds 1000 {label} lifestyle experience."
    for t in EK2_TREES:
        T = t.capitalize()
        loc[f"UCM_SEC_EK2_TREE_{t.upper()}"] = T
        loc[f"ucm_ek2_perks_{t}"] = f"All {T} Perks"
        loc[f"ucm_ek2_perks_{t}_tt"] = f"Unlocks every perk in the {T} tree."
        for r in EK2_PERK_RANKS:
            loc[f"ucm_ek2_perk_{perk(t, r)}"] = f"${perk(t, r)}_name$"
            loc[f"ucm_ek2_perk_{perk(t, r)}_tt"] = "Grants this perk only. Disabled once the character has it."
    write("localization/english/ucm_ek2_l_english.yml", "l_english:\n" + "".join(f' {k}: "{v}"\n' for k, v in loc.items()), bom=True)
    print(f"{len(names)} scripted GUIs")


if __name__ == "__main__":
    main()
