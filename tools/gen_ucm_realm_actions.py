def localization(game):
    vanilla = ck3parse.load_loc("english", game)
    for law in [r[0] for r in REALM_LAWS] + list(GENDER_LAWS) + list(HOLDINGS):
        assert law in vanilla, law
    for i, lang in enumerate(LANGS):
        lines = [f'l_{lang}:']
        lines += [f' {k}: "{v[i]}"' for k, v in TEXT.items() if k != "ucm_holding_realm_label"]
        for law in [r[0] for r in REALM_LAWS] + list(GENDER_LAWS):
            lines += [f' ucm_law_{law}: "${law}$"', f' ucm_law_{law}_tt: "$ucm_law_pick_tt$"']
        for h in HOLDINGS:
            lines += [f' ucm_holding_capital_{h}: "${h}$"', f' ucm_holding_capital_{h}_tt: "$ucm_holding_capital_tt$"']
        for h in REALM_HOLDINGS:
            label = TEXT["ucm_holding_realm_label"][i].replace("$WHAT$", f"${h}$")
            lines += [f' ucm_holding_realm_{h}: "{label}"', f' ucm_holding_realm_{h}_tt: "$ucm_holding_realm_tt$"']
        write(f"localization/{lang}/ucm_realm_actions_l_{lang}.yml", "\n".join(lines) + "\n", bom=True)


