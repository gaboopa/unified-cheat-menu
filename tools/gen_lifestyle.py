"""Generate the classic-menu lifestyle cheat pages and the perk option labels from the CK3 perk database.

Writes events/ucm_lifestyle_cheat_generated.txt (hub 0600, one page per lifestyle, paged perk toggles, reset
confirmations) and localization/<lang>/ucm_lifestyle_perk_options_l_<lang>.yml (ucm_lsf.pk_<perk> = the game's
perk name; gendered perks also get _male/_female keys). The labels cover every perk, wanderer included, because
gui/ucm_lifestyle.gui uses them too. The event pages cover the five skill lifestyles; wanderer only has the reset
event 0690 (opened from the GUI).

Perks are grouped by TREES (order shown) and sorted by id within a tree. A tree missing from TREES stops the
script.

Run after a CK3 update:
    python tools/gen_lifestyle.py --game-dir <CK3>/game
or set CK3_GAME_DIR instead of passing the flag.
"""
import argparse
import os
import re
import sys

from ck3parse import effective_files, load_loc, top_level_objects

MOD_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_REL = os.path.join("events", "ucm_lifestyle_cheat_generated.txt")
PERKS = os.path.join("common", "lifestyle_perks")
LANGS = ["english", "german", "russian", "simp_chinese"]
PAGE_SIZE = 6
# lifestyle -> trees in display order. Event ids: lifestyle page 0601+i, perk pages from 0610+15*i, reset 0685+i.
TREES = {"diplomacy": ["family", "majesty", "foreign_affairs"], "martial": ["authority", "chivalry", "strategy"],
         "stewardship": ["domain", "duty", "wealth"], "intrigue": ["skulduggery", "intimidation", "temptation"],
         "learning": ["medicine", "theology", "scholarship"]}
OTHER_TREES = {"surveyor", "wayfarer", "voyager"}  # wanderer: labels only
XP = [250, 1000, 3000]
EXTRA_TRAIT = {"family_man_perk": "family_first"}  # toggled along with the perk (kept from Skonester's pages)

TARGET_ON = ["trigger = {", "  ucm_cheat_menu_menu_enabled_trigger = yes", "  exists = scope:ucm_lifestyle_target", "}"]


def eid(n):
    return f"{n:04d}"


def option(name, body, on=True):
    return ["  option = {", f"    name = {name}"] + [f"    {line}" for line in (TARGET_ON if on else []) + body] + ["  }"]


def go(n):
    return ["scope:actor = {", f"  trigger_event = ucm_cheat_menu.{eid(n)}", "}"]


def on_target(*lines):
    return ["scope:ucm_lifestyle_target = {"] + [f"  {line}" for line in lines] + ["}"]


def event(n, title, opts):
    return [f"ucm_cheat_menu.{eid(n)} = {{", "  type = character_event", f"  title = {title}",
            "  desc = ucm_ui_no_hover_tooltip", "  theme = learning", "  right_portrait = scope:ucm_lifestyle_target",
            "  immediate = {", "    ucm_cheat_menu_sync_lifestyle_target_effect = yes", "  }"] + opts + ["}"]


CLOSE = ["  option = { name = ucm_cheat_menu.00x.close }"]


def load(game):
    """{tree: [perk, ...]} from the game's perk files."""
    trees = {}
    for f in effective_files(PERKS, game):
        for k, b in top_level_objects(f):
            trees.setdefault(re.search(r"\btree\s*=\s*(\w+)", b).group(1), []).append(k)
    unknown = set(trees) - {t for ts in TREES.values() for t in ts} - OTHER_TREES
    if unknown:
        sys.exit(f"perk trees not in TREES: {', '.join(sorted(unknown))}")
    return {t: sorted(ps) for t, ps in trees.items()}


def build(trees):
    L = ["namespace = ucm_cheat_menu",
         "## AUTO-GENERATED by tools/gen_lifestyle.py from the CK3 perk database. Do not edit; rerun the script.",
         "## Perk option labels: name = ucm_lsf.pk_<perk_id>, in localization/*/ucm_lifestyle_perk_options_l_*.yml (same script)."]
    hub = [o for i, ls in enumerate(TREES) for o in option(f"ucm_lsf.open_{ls}", go(601 + i))]
    for x in XP:
        hub += option(f"ucm_lsf.all_xp_{x}", on_target(*[f"add_{ls}_lifestyle_xp = {x}" for ls in TREES]) + go(600))
    L += event(600, "ucm_lsf.hub_t", hub + CLOSE)
    for i, (ls, ts) in enumerate(TREES.items()):
        page, first, reset = 601 + i, 610 + 15 * i, 685 + i
        perks = [p for t in ts for p in trees.get(t, [])]
        chunks = [perks[j:j + PAGE_SIZE] for j in range(0, len(perks), PAGE_SIZE)]
        if len(chunks) > 15:
            sys.exit(f"{ls}: {len(chunks)} perk pages do not fit in 15 event ids")
        opts = [o for x in XP for o in option(f"ucm_lsf.xp_{x}", on_target(f"add_{ls}_lifestyle_xp = {x}") + go(page))]
        opts += [o for x in (1, 3) for o in option(f"ucm_lsf.add_perk_point_{x}", on_target(f"add_{ls}_lifestyle_perk_points = {x}") + go(page))]
        opts += option("ucm_lsf.reset_tree", go(reset)) + option("ucm_lsf.open_perk_pages", go(first))
        L += event(page, f"ucm_lsf.{ls}_t", opts + option("ucm_cheat_menu.00x.back", go(600)) + CLOSE)
        for j, chunk in enumerate(chunks):
            n = first + j
            opts = option("ucm_cheat_menu.page_prev", go(n - 1)) if j else []
            for p in chunk:
                t = EXTRA_TRAIT.get(p)
                opts += option(f"ucm_lsf.pk_{p}", on_target(
                    "if = {", f"  limit = {{ has_perk = {p} }}", f"  remove_perk = {p}", *([f"  remove_trait = {t}"] if t else []),
                    "}", "else = {", f"  add_perk = {p}", *([f"  add_trait = {t}"] if t else []), "}") + go(n))
            if j + 1 < len(chunks):
                opts += option("ucm_cheat_menu.page_next", go(n + 1))
            L += event(n, f"ucm_lsf.{ls}_perks_t", opts + option("ucm_cheat_menu.00x.back", go(page)) + CLOSE)
        L += event(reset, "ucm_lsf.reset_confirm_t", option("ucm_lsf.reset_yes", on_target(f"refund_perks = {ls}_lifestyle") + go(page))
                   + option("ucm_lsf.reset_no", go(page), on=False))
    L += event(690, "ucm_lsf.reset_confirm_t", option("ucm_lsf.reset_yes", on_target("refund_perks = wanderer_lifestyle"))
               + option("ucm_lsf.reset_no", [], on=False))
    return "\n".join(L) + "\n"


def loc_file(lang, perks, loc):
    """<perk>_name, or for a gendered perk its _male_name (plus _female/_male keys for the GUI)."""
    L = [f"l_{lang}:"]
    for p in sorted(perks):
        gendered = [(p, f"{p}_male_name"), (f"{p}_female", f"{p}_female_name"), (f"{p}_male", f"{p}_male_name")]
        for k, src in [(p, f"{p}_name")] if f"{p}_name" in loc else gendered:
            if src not in loc:
                sys.exit(f"{lang}: no localization {src} for perk {p}")
            L.append(f' ucm_lsf.pk_{k}: "{loc[src]}"')
    return "\n".join(L) + "\n"


def write(path, text):
    with open(path, "wb") as fh:
        fh.write(b"\xef\xbb\xbf" + text.replace("\n", "\r\n").encode("utf-8"))
    print("wrote", os.path.relpath(path, MOD_DIR))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--game-dir", default=os.environ.get("CK3_GAME_DIR"), help="CK3 game/ directory (or CK3_GAME_DIR)")
    args = ap.parse_args()
    if not args.game_dir or not os.path.isdir(os.path.join(args.game_dir, PERKS)):
        sys.exit(f"--game-dir: no {PERKS} under {args.game_dir!r}")
    trees = load(args.game_dir)
    write(os.path.join(MOD_DIR, OUT_REL), build(trees))
    for lang in LANGS:
        write(os.path.join(MOD_DIR, "localization", lang, f"ucm_lifestyle_perk_options_l_{lang}.yml"),
              loc_file(lang, [p for ps in trees.values() for p in ps], load_loc(lang, args.game_dir)))


if __name__ == "__main__":
    main()
