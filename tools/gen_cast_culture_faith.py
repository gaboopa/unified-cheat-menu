"""Generate the classic-menu culture casting pages from the CK3 culture database.

Writes events/ucm_cast_culture_faith_generated.txt (heritage hub + per-heritage culture pages) and
localization/<lang>/ucm_cast_culture_faith_generated_l_<lang>.yml (the culture option labels, from the game's
own culture names). The hub's heritage labels are hand-translated in ucm_cast_culture_faith_hotfix_l_<lang>.yml;
the script lists any heritage missing there. gen_ek2_compatch.py writes the EK2 stub with ek2_stub().

The faith half of the original pages (3300+) was removed as unreachable, so only cultures are generated.
Hub: HUB_ID onward (HUB_ID is referenced from .0021). Culture pages: 3100 onward, skipping the hub's ids.

Run after a CK3 update:
    python tools/gen_cast_culture_faith.py --game-dir <CK3>/game
or set CK3_GAME_DIR instead of passing the flag.
"""
import argparse
import os
import re
import sys
from collections import defaultdict

from ck3parse import LOC_LINE, effective_files, load_loc, top_level_objects

MOD_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_REL = os.path.join("events", "ucm_cast_culture_faith_generated.txt")
CULTURES = os.path.join("common", "culture", "cultures")
HUB_ID, PAGE_ID, ID_LIMIT = 3186, 3100, 3500  # 3500+ is the beauty companion
HUB_PER_PAGE, PER_PAGE = 7, 4
# Label suffix per language (Russian shows the plain culture name).
LANGS = {"english": " [Edit]", "german": " [Edit]", "russian": "", "simp_chinese": " · 修改"}

ON = "trigger = { ucm_cheat_menu_menu_enabled_trigger = yes }"
COMPANION = "has_character_flag = ucm_companion_picking_culture"
REFORM = "has_character_flag = ucm_culture_reform_pick"
BACK_COMPANION = (f"if = {{ limit = {{ scope:recipient = {{ {COMPANION} }} }} scope:recipient = {{ remove_character_flag = "
                  f"ucm_companion_picking_culture }} trigger_event = ucm_cheat_menu.0180 }}")
CLOSE = (f"  option = {{ name = ucm_cheat_menu.00x.close {ON} root = {{ {BACK_COMPANION} else_if = {{ limit = {{ {REFORM} }} "
         f"remove_character_flag = ucm_culture_reform_pick trigger_event = ucm_cheat_menu.0021 }} }} }}")
HUB_BACK = (f"  option = {{ name = ucm_cheat_menu.0185.back_hub {ON} root = {{ {BACK_COMPANION} else_if = {{ limit = {{ {REFORM} }} "
            f"remove_character_flag = ucm_culture_reform_pick trigger_event = ucm_cheat_menu.0021 }} else = {{ "
            f"ucm_cf_culture_faith_quick_hub_back_or_main_effect = yes }} }} }}")


def go(name, eid):
    return f"  option = {{ name = {name} {ON} root = {{ trigger_event = ucm_cheat_menu.{eid} }} }}"


def pick(c, eid):
    return (f"  option = {{ name = culture_{c} {ON} scope:recipient = {{ if = {{ limit = {{ {COMPANION} }} set_variable = {{ "
            f"name = ucm_companion_stored_culture value = culture:{c} }} }} else_if = {{ limit = {{ root = {{ {REFORM} }} }} "
            f"ucm_culture_reform_skip_recipient_culture_effect = yes }} else = {{ set_culture = culture:{c} }} }} root = {{ "
            f"{BACK_COMPANION} else_if = {{ limit = {{ {REFORM} }} remove_character_flag = ucm_culture_reform_pick "
            f"set_culture = culture:{c} trigger_event = ucm_cheat_menu.0120 }} else = {{ trigger_event = ucm_cheat_menu.{eid} }} }} }}")


def event(eid, title, opts):
    return [f"ucm_cheat_menu.{eid} = {{", "  type = character_event", f"  title = ucm_cheat_menu.0185.{title}",
            "  desc = ucm_ui_no_hover_tooltip", "  theme = default", "  right_portrait = scope:recipient", ""] + opts + ["}", ""]


def pages(items, n):
    return [items[i:i + n] for i in range(0, len(items), n)]


def nav(ids, i):
    return ([go("ucm_cheat_menu.page_prev", ids[i - 1])] if i else []) + \
           ([go("ucm_cheat_menu.page_next", ids[i + 1])] if i + 1 < len(ids) else [])


def load(dirs):
    """{heritage suffix: [culture, ...]}, both sorted by key."""
    by = defaultdict(list)
    for f in effective_files(CULTURES, *dirs):
        for k, b in top_level_objects(f):
            m = re.search(r"\bheritage\s*=\s*heritage_(\w+)", b)
            if not m:
                sys.exit(f"culture {k}: no heritage")
            by[m.group(1)].append(k)
    return {h: sorted(cs) for h, cs in sorted(by.items())}


def build(her):
    hub_pages = pages(list(her), HUB_PER_PAGE)
    hub_ids = list(range(HUB_ID, HUB_ID + len(hub_pages)))
    free = (i for i in range(PAGE_ID, ID_LIMIT) if i not in hub_ids)
    page_ids = {h: [next(free) for _ in pages(cs, PER_PAGE)] for h, cs in her.items()}
    if max(max(ids) for ids in page_ids.values()) >= ID_LIMIT or hub_ids[-1] >= ID_LIMIT:
        sys.exit(f"casting pages ran past ucm_cheat_menu.{ID_LIMIT}; move ID_LIMIT/PAGE_ID")
    L = ["namespace = ucm_cheat_menu", "", "## AUTO-GENERATED by tools/gen_cast_culture_faith.py from the CK3 culture database. "
         "Do not edit; rerun the script.",
         f"## Heritage hub at {hub_ids[0]}-{hub_ids[-1]}, culture pages from {PAGE_ID} (skipping the hub).", ""]
    for i, hs in enumerate(hub_pages):
        L += event(hub_ids[i], "culture_heritage_t", [go(f"ucm_cast_hf_{h}", page_ids[h][0]) for h in hs] + [""]
                   + nav(hub_ids, i) + [HUB_BACK, CLOSE])
    for h, cs in her.items():
        ids = page_ids[h]
        for i, chunk in enumerate(pages(cs, PER_PAGE)):
            L += event(ids[i], "culture_picker_t", [pick(c, ids[i]) for c in chunk] + [""] + nav(ids, i)
                       + [go("ucm_cheat_menu.0185.back_hub", HUB_ID), CLOSE])
    return "\n".join(L)


def ek2_stub():
    """EK2 has none of the vanilla cultures: keep only the hub id (referenced from .0021), opening the runtime picker."""
    return "\n".join(["namespace = ucm_cheat_menu", "",
                      "## AUTO-GENERATED by tools/gen_ek2_compatch.py (tools/gen_cast_culture_faith.py). EK2 stub: the "
                      f"vanilla culture pages are dropped; .{HUB_ID} opens the runtime picker instead.", ""]
                     + event(HUB_ID, "culture_heritage_t", [
                         "  option = { name = ucm_cheat_menu.1420.browse_all_flat root = { ucm_open_acm_culture_picker_effect = yes } }",
                         "  option = { name = ucm_cheat_menu.00x.close }"]))


def loc_file(lang, her, names):
    L = [f"l_{lang}:"]
    for c in sorted(c for cs in her.values() for c in cs):
        if c not in names:
            sys.exit(f"{lang}: no localization for culture {c}")
        L.append(f' culture_{c}: "{names[c]}{LANGS[lang]}"')
    return "\n".join(L) + "\n"


def check_hub_labels(lang, her):
    path = os.path.join(MOD_DIR, "localization", lang, f"ucm_cast_culture_faith_hotfix_l_{lang}.yml")
    have = load_loc_file(path)
    missing = [h for h in her if f"ucm_cast_hf_{h}" not in have]
    if missing:
        print(f"  {os.path.relpath(path, MOD_DIR)}: add hub labels for", ", ".join(f"ucm_cast_hf_{h}" for h in missing))


def load_loc_file(path):
    with open(path, encoding="utf-8-sig") as fh:
        return dict(LOC_LINE.findall(fh.read()))


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as fh:
        fh.write(b"\xef\xbb\xbf" + text.replace("\n", "\r\n").encode("utf-8"))
    print("wrote", os.path.relpath(path, MOD_DIR))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--game-dir", default=os.environ.get("CK3_GAME_DIR"), help="CK3 game/ directory (or CK3_GAME_DIR)")
    args = ap.parse_args()
    if not args.game_dir or not os.path.isdir(os.path.join(args.game_dir, CULTURES)):
        sys.exit(f"--game-dir: no {CULTURES} under {args.game_dir!r}")
    her = load([args.game_dir, MOD_DIR])
    write(os.path.join(MOD_DIR, OUT_REL), build(her))
    for lang in LANGS:
        write(os.path.join(MOD_DIR, "localization", lang, f"ucm_cast_culture_faith_generated_l_{lang}.yml"),
              loc_file(lang, her, load_loc(lang, args.game_dir)))
        check_hub_labels(lang, her)


if __name__ == "__main__":
    main()
