def char_sets(prefix, sets):
    out = ""
    for i, (kind, limit) in enumerate(sets, 1):
        inner = f" limit = {{ {limit} }}" if limit else ""
        out += f"\t\t\t{prefix}_{i} = {{ type = {kind}{inner} }}\n"
    return out


